#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Append this paper's artefacts to proof_graph/artifacts.yaml (idempotent).

Why a script rather than an editor: ``artifacts.yaml`` is UTF-8 without BOM,
LF-only, and parsed by ``tools/artifact_lint.py`` (L8).  A YAML round-trip would
reorder and re-quote the whole 1395-line ledger; a byte-surgical append of the
well-formed block at end of file touches nothing that already exists.

Every entry must carry ``owner`` (a graph node or a sentinel) and ``consumer``
(a sentence naming who needs it), per ARTIFACT_SPEC §2/§10 L8.  The owner here is
the node this paper reports, which exists in ``theory_graph.yaml``.

Re-running is a no-op: entries are matched by ``path``.
"""
from __future__ import annotations

import io
import sys
from pathlib import Path

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[3]   # E:\study\AImath
LEDGER = ROOT / "proof_graph" / "artifacts.yaml"
OWNER = "PPHI2_FIXED_VOLUME_FREE_FIELD_MEASURE_LIMIT"
ASOF = "2026-11-02"

ENTRIES = [
    ("deliverables/20261102_pphi2_fixed_volume_complete.pdf",
     "Compiled arXiv-style manuscript (39 pp, Part I mathematics and Part II Lean 4) of the "
     "fixed-volume H^-3 weak-limit result; rebuilt by paper/PPHI2_FIXED_VOLUME_COMPLETE/build_all.py"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/main.tex",
     "Assembly file of the fixed-volume H^-3 weak-limit paper (frozen preamble, macros, title, "
     "abstract, input order); body in sections/, counts and both appendices generated by audit/*.py"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/README.md",
     "Reader entry point: layout, build, what the four paper checks verify and what they cannot"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/build_all.py",
     "Single build entry point: regenerate counts/ledger/bibliography, run the gate with its negative "
     "controls, compile with Tectonic from a project-local cache, stamp every source hash"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/refs.bib",
     "Single source of truth for the bibliography; rendered to generated/bibliography.tex by "
     "audit/make_bib.py because the offline Tectonic bundle carries no .bst files"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/audit/count_lean.py",
     "Recomputes every structural count from the Lean sources and the contract registry into "
     "generated/metrics.tex, so no count in the prose can rot"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/audit/make_ledger.py",
     "Renders Appendix A (declaration ledger) from the statement registry and Appendix B (footprint "
     "transcript) from ext/axiom_transcript.txt, refusing to run if the two disagree"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/audit/make_bib.py",
     "Renders refs.bib into an explicit thebibliography environment; the offline bundle has no .bst, "
     "and BibTeX's failure is swallowed by the driver, which would leave every citation as [?]"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/audit/verify_paper.py",
     "The paper's assertion gate (four checks, eleven negative controls): quoted Lean names exist, "
     "counts are macros, labels/refs/citations close, footprints and ledger stay consistent"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/ext/axiom_transcript.txt",
     "Recorded verbatim engine transcript of #print axioms for the ten reported declarations, with "
     "the project, toolchain, date and exact commands that produced it"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/notes/paper_ledger.md",
     "Paper-level proof inventory the article was written from: 59 lemma-level entries with "
     "document:line pointers, the analytic content a paper must carry, and the ranked gap list"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/notes/lean_ledger.md",
     "Formal-side inventory: module map, declaration and definition ledgers, axiom footprint, and the "
     "honest gap list (reachability, the vacuous wrapper, the unused null-set convention)"),
    ("paper/PPHI2_FIXED_VOLUME_COMPLETE/notes/CONTRACT.md",
     "Writing contract the parallel writers were held to: the claim and its prohibitions, ownership, "
     "frozen preamble, label table, number and citation discipline, and the formal-side traps"),
]


def main() -> int:
    text = LEDGER.read_text(encoding="utf-8")
    if not text.endswith("\n"):
        raise SystemExit("PREFLIGHT FAIL: artifacts.yaml does not end with a newline")
    added, skipped = [], []
    block = []
    for path, consumer in ENTRIES:
        key = "  - path: %s\n" % path
        if key in text:
            skipped.append(path)
            continue
        block.append(key)
        block.append("    owner: %s\n" % OWNER)
        block.append('    consumer: "%s"\n' % consumer)
        block.append("    status: ACTIVE\n")
        block.append("    asof: %s\n" % ASOF)
        added.append(path)
    if not block:
        print("no-op: every entry already registered (%d)" % len(skipped))
        return 0
    LEDGER.write_text(text + "".join(block), encoding="utf-8", newline="\n")
    print("appended %d entries, skipped %d already present" % (len(added), len(skipped)))
    for p in added:
        print("  + " + p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
